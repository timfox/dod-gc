#!/usr/bin/env python3
"""The sounds the retail DoD view models play, from their animation events.

Retail DoD plays the reload, draw and bolt-cycle sounds from event 5004 entries inside the view model's sequences
("weapons/tommy_reload_clipout.wav" at frame 12 of the MP40 reload, "weapons/boltback.wav" in the Kar98k shot, ...);
they are not part of the game DLL. The GameCube DoD route does not run view model events, so the game code plays them
itself at the same time offsets. This tool reads the events out of the retail models for the sequences
tools/gen_viewanims.py names and writes src/dod_viewsounds.h.

  tools/gen_viewsounds.py --models <dod>/models --write src/dod_viewsounds.h
  tools/gen_viewsounds.py --models <dod>/models --check src/dod_viewsounds.h
"""
import argparse
import importlib.util
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("gen_viewanims", HERE / "gen_viewanims.py")
ANIMS = importlib.util.module_from_spec(_spec)
sys.modules[_spec.name] = ANIMS
_spec.loader.exec_module(ANIMS)

EVENT_SOUND = 5004
ROLES = (("DOD_ANIM_FIRE", "fire"), ("DOD_ANIM_RELOAD", "reload"), ("DOD_ANIM_DRAW", "draw"))
MAX_EVENTS = 8


def sequence_events(path):
    """Per sequence: (fps, [(frame, sound)]) for the 5004 events, as the studio header lays them out."""
    data = Path(path).read_bytes()
    if data[:4] != b"IDST":
        raise ValueError(f"{path}: not a studio model")
    numseq, seqindex = struct.unpack_from("<ii", data, 164)
    out = []
    for i in range(numseq):
        base = seqindex + i * 176
        fps, _flags, _act, _actw, nev, evidx = struct.unpack_from("<fiiiii", data, base + 32)
        events = []
        for e in range(nev):
            frame, event, _type = struct.unpack_from("<3i", data, evidx + e * 76)
            if event != EVENT_SOUND:
                continue
            name = data[evidx + e * 76 + 12:evidx + e * 76 + 76].split(b"\0")[0].decode("latin1")
            events.append((frame, name))
        out.append((fps, sorted(events)))
    return out


def collect(models_dir):
    rows = []
    for model, spec in sorted(ANIMS.MODELS.items()):
        path = Path(models_dir) / f"{model}.mdl"
        resolved = ANIMS.resolve(model, spec, ANIMS.sequence_labels(path))
        seqs = sequence_events(path)
        for const, role in ROLES:
            seq = resolved[role][0] if role == "fire" and resolved[role] else resolved[role]
            if role == "fire" and not resolved[role]:
                continue
            if seq is None or seq < 0:
                continue
            fps, events = seqs[seq]
            if not events:
                continue
            if len(events) > MAX_EVENTS:
                raise ValueError(f"{model} {role}: {len(events)} events, the table holds {MAX_EVENTS}")
            timed = [(int(round(frame * 1000.0 / fps)), name) for frame, name in events]
            rows.append((model, const, timed))
    return rows


def render(rows):
    lines = ["/* Generated by tools/gen_viewsounds.py from the retail DoD view models. Do not edit.",
             " * model, role, count, { milliseconds into the sequence, sound } (retail animation event 5004). */"]
    for model, const, timed in rows:
        ev = ", ".join('{ %d, "%s" }' % (ms, name) for ms, name in timed)
        lines.append('\t{ "models/%s.mdl", %s, %d, { %s } },' % (model, const, len(timed), ev))
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--models", type=Path, required=True, help="the retail dod/models directory")
    ap.add_argument("--write", type=Path)
    ap.add_argument("--check", type=Path, help="exit 1 when this header is not what the models render")
    args = ap.parse_args(argv)
    text = render(collect(args.models))
    if args.write:
        args.write.write_text(text)
        print(f"wrote {args.write}")
    if args.check and args.check.read_text() != text:
        print(f"{args.check} is out of date; run with --write", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
